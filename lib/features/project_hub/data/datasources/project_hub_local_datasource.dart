  List<Project> getFeaturedProjects() =>
      getProjects().where((p) => p.isFeatured).toList();

  List<Project> getNewProjects() =>
      getProjects().where((p) => p.isNew).toList();

  List<Project> searchProjects(String query) {
    final lowerQuery = query.toLowerCase();
    return getProjects().where((p) =>
        p.name.toLowerCase().contains(lowerQuery) ||
        p.description.toLowerCase().contains(lowerQuery) ||
        p.technologies.any((t) => t.toLowerCase().contains(lowerQuery)) ||
        p.tags.any((t) => t.toLowerCase().contains(lowerQuery))).toList();
  }

  List<Project> getProjectsByDifficulty(ProjectDifficulty difficulty) =>
      getProjects().where((p) => p.difficulty == difficulty).toList();

  List<Project> getProjectsByCategory(ProjectCategory category) =>
      getProjects().where((p) => p.category == category).toList();

  List<Project> getProjectsByTechnology(String tech) =>
      getProjects().where((p) => p.technologies.contains(tech)).toList();

  List<ProjectRecommendation> getRecommendations(List<String> userSkills) {
    final allProjects = getProjects();
    final recommendations = <ProjectRecommendation>[];
    for (final project in allProjects) {
      int matchCount = 0;
      final reasons = <String>[];
      for (final tech in project.technologies) {
        if (userSkills.contains(tech)) {
          matchCount++;
          reasons.add('Matches your $tech skills');
        }
      }
      if (matchCount > 0) {
        final score = ((matchCount / project.technologies.length) * 100).round();
        recommendations.add(ProjectRecommendation(
          project: project,
          matchScore: score.clamp(20, 100),
          reasons: reasons,
        ));
      }
    }
    recommendations.sort((a, b) => b.matchScore.compareTo(a.matchScore));
    return recommendations.take(8).toList();
  }

  List<String> getAllTechnologies() {
    final techs = <String>{};
    for (final p in getProjects()) {
      techs.addAll(p.technologies);
    }
    return techs.toList()..sort();
  }
